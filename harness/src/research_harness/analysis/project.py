"""Per-object ``uv`` analysis project (M3-18, analysis-sandbox.md).

``rh analysis init`` writes ``analysis/pyproject.toml`` with pinned base packages.
The lockfile (``analysis/uv.lock``) is produced by ``uv`` from a network index,
so it is not generated here (invariant 2 keeps the network off at run time, and
this harness does not fetch packages for the author); the project is ready for
``uv lock`` / ``uv sync`` the author or the first run performs.
"""

from __future__ import annotations

from pathlib import Path

# Base scientific stack, pinned (analysis-sandbox.md). Versions are explicit so
# the project resolves reproducibly; the author may widen them in pyproject.
BASE_PACKAGES: tuple[tuple[str, str], ...] = (
    ("numpy", "2.1.3"),
    ("pandas", "2.2.3"),
    ("scipy", "1.14.1"),
    ("statsmodels", "0.14.4"),
    ("matplotlib", "3.9.2"),
)

_REQUIRES_PYTHON = ">=3.11"


def project_dir(root: Path) -> Path:
    return root / "analysis"


def pyproject_path(root: Path) -> Path:
    return project_dir(root) / "pyproject.toml"


def render_pyproject() -> str:
    deps = ",\n".join(f'    "{name}=={ver}"' for name, ver in BASE_PACKAGES)
    return (
        "# Generated by `rh analysis init` (M3-18). Per-object analysis sandbox.\n"
        "[project]\n"
        'name = "rh-analysis"\n'
        'version = "0.0.0"\n'
        'description = "Reproducible analysis sandbox for one research object."\n'
        f'requires-python = "{_REQUIRES_PYTHON}"\n'
        "dependencies = [\n"
        f"{deps},\n"
        "]\n\n"
        "[tool.uv]\n"
        "# The sandbox runs with the network disabled; resolve/sync beforehand.\n"
        "package = false\n"
    )


def init(root: Path) -> dict[str, object]:
    """Create ``analysis/`` with a pinned pyproject; idempotent (keeps an edited
    pyproject if one already exists). Returns a small report."""
    d = project_dir(root)
    (d / "scripts").mkdir(parents=True, exist_ok=True)
    (d / "data").mkdir(parents=True, exist_ok=True)
    (d / "datasets").mkdir(parents=True, exist_ok=True)
    path = pyproject_path(root)
    created = not path.is_file()
    if created:
        path.write_text(render_pyproject(), encoding="utf-8")
    return {
        "dir": str(d),
        "pyproject": str(path),
        "created": created,
        "packages": [f"{n}=={v}" for n, v in BASE_PACKAGES],
        "lockfile_present": (d / "uv.lock").is_file(),
    }
